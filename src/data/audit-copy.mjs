/**
 * The four failure states, each a title and a body, and each with the status code it answers with.
 *
 * The status code is here rather than in the route because it is part of what the state *is*: a
 * refused address is a 400 whether it was reached from a form or from a link, and keeping the pair
 * together is what stops the page and the header disagreeing about what happened.
 *
 * Title and body both take the same `{ origin, time }` bag rather than positional arguments, so a
 * caller never has to know which of the two a given state happens to name.
 */
export const ERRORS = {
  'rate-limited': {
    status: 429,
    title: () => 'Too many audits for now',
    body: ({ time }) => `Try again after ${time}.`,
  },
  'bad-address': {
    status: 400,
    title: () => 'That address cannot be audited',
    body: () => 'Enter a public website address, starting with http or https.',
  },
  refused: {
    status: 502,
    title: ({ origin }) => `${origin} did not answer`,
    body: () => 'The site refused the audit or could not be reached. Nothing was checked.',
  },
  timeout: {
    status: 504,
    title: () => 'The audit ran out of time',
    body: ({ origin }) => `${origin} answered too slowly to finish. Try again later.`,
  },
};

/**
 * The four error states as the template reads them: title and body already resolved.
 *
 * @param {'rate-limited' | 'bad-address' | 'refused' | 'timeout'} kind
 * @param {{ origin?: string, time?: string }} values
 */
export function errorView(kind, values = {}) {
  const spec = ERRORS[kind];
  const bag = { origin: values.origin ?? '', time: values.time ?? '' };
  return { kind, status: spec.status, title: spec.title(bag), body: spec.body(bag) };
}
