/**
 * Refresh src/data/bot-ranges.mjs from the IP range lists Google and OpenAI publish.
 *
 * Run by hand: `node scripts/refresh-bot-ranges.mjs`, then commit the diff. Never at build and
 * never at request time. The ranges are DATA: src/lib/web-bot-auth.mjs reads them from the
 * committed file, so the middleware never fetches a range list and a vendor's outage never
 * reaches a request. The cost is staleness, and the file says how stale: `fetched` is the date
 * this script ran, and each source keeps the `creationTime` its publisher stamped on it.
 *
 * A range list is the evidence behind the `ip-verified` state, so the family each list vouches for
 * is decided here, in SOURCES, and nowhere else. A family missing from SOURCES can be `signed` or
 * `claimed` but never `ip-verified`.
 *
 * Fails loudly, writes nothing, on any source that does not answer with the expected shape: a
 * half-refreshed file would quietly turn one family's verified traffic into claimed traffic.
 *
 * A module rather than a JSON file, like src/data/page-paths.mjs. The middleware imports it, Node
 * imports JSON only with an import attribute, and the bundler Vercel runs over middleware.ts
 * rejects that syntax (the first preview build, 2026-10-17: `Expected ";" but found "with"`).
 *
 * NO TOP-LEVEL SIDE EFFECTS beyond the run at the foot of the file, which only happens when this
 * script is the entry point, so tests/web-bot-auth.test.mjs can import the normaliser.
 */

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

/**
 * Which published list vouches for which client family. Family names are the ones
 * CLIENT_FAMILIES in src/lib/agent-hits.mjs assigns.
 *
 * Google: https://developers.google.com/crawling/docs/crawlers-fetchers/verify-google-requests
 * OpenAI: https://platform.openai.com/docs/bots
 */
export const SOURCES = [
  { family: 'googlebot', url: 'https://developers.google.com/static/crawling/ipranges/common-crawlers.json' },
  { family: 'googleother', url: 'https://developers.google.com/static/crawling/ipranges/common-crawlers.json' },
  { family: 'google-agent', url: 'https://developers.google.com/static/crawling/ipranges/user-triggered-fetchers.json' },
  {
    family: 'google-agent',
    url: 'https://developers.google.com/static/crawling/ipranges/user-triggered-fetchers-google.json',
  },
  { family: 'gptbot', url: 'https://openai.com/gptbot.json' },
  { family: 'oai-searchbot', url: 'https://openai.com/searchbot.json' },
  { family: 'chatgpt-user', url: 'https://openai.com/chatgpt-user.json' },
];

/** IPv4 or IPv6 CIDR, the only two shapes either publisher uses. */
const CIDR = /^(?:\d{1,3}(?:\.\d{1,3}){3}\/\d{1,2}|[0-9a-f:]+\/\d{1,3})$/i;

/**
 * One published list, as a sorted array of CIDR strings plus the publisher's own timestamp. Both
 * publishers use the same shape: `{ creationTime, prefixes: [{ ipv4Prefix } | { ipv6Prefix }] }`.
 *
 * @param {unknown} body
 * @returns {{ creationTime: string | null, prefixes: string[] }}
 */
export function normaliseRangeList(body) {
  if (!body || typeof body !== 'object' || !Array.isArray(body.prefixes)) {
    throw new Error('range list has no prefixes array');
  }
  const prefixes = body.prefixes
    .map((entry) => entry?.ipv4Prefix ?? entry?.ipv6Prefix)
    .filter((prefix) => typeof prefix === 'string' && CIDR.test(prefix))
    .map((prefix) => prefix.toLowerCase());
  if (prefixes.length === 0) throw new Error('range list has no usable prefixes');
  return {
    creationTime: typeof body.creationTime === 'string' ? body.creationTime : null,
    prefixes: [...new Set(prefixes)].sort(),
  };
}

/** Today's date on Matt's clock, which is the date every file in this repo is stamped with. */
function localDate(now = new Date()) {
  return new Intl.DateTimeFormat('en-CA', { timeZone: 'America/Vancouver' }).format(now);
}

async function refresh() {
  const sources = [];
  for (const { family, url } of SOURCES) {
    const response = await fetch(url, { headers: { Accept: 'application/json' }, redirect: 'error' });
    if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
    const list = normaliseRangeList(await response.json());
    sources.push({ family, url, ...list });
    console.log(`${family.padEnd(14)} ${String(list.prefixes.length).padStart(4)} prefixes  ${url}`);
  }

  const target = fileURLToPath(new URL('../src/data/bot-ranges.mjs', import.meta.url));
  writeFileSync(target, renderRangesModule({ fetched: localDate(), sources }));
  console.log(`wrote ${target}`);
}

/**
 * The committed module's text: a header, then one exported object.
 *
 * @param {{ fetched: string, sources: Array<{ family: string, url: string,
 *           creationTime: string | null, prefixes: string[] }> }} data
 */
export function renderRangesModule(data) {
  return [
    '// GENERATED BY scripts/refresh-bot-ranges.mjs. DO NOT EDIT BY HAND.',
    '//',
    '// Published IP ranges per client family, the evidence for the ip-verified state in',
    '// src/lib/web-bot-auth.mjs. Data, not a runtime fetch: refresh with',
    '// `node scripts/refresh-bot-ranges.mjs` and commit the diff. `fetched` is the local date it ran.',
    '',
    `export const BOT_RANGES = ${JSON.stringify(data, null, 2)};`,
    '',
  ].join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  refresh().catch((error) => {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  });
}
